import type { CardDef, CardKind, ColorId, Rarity } from './types';

function card(
  id: string,
  setId: string,
  name: string,
  subtitle: string,
  color: ColorId,
  rarity: Rarity,
  cost: number,
  motif: string,
  extras: { power?: number; counter?: number; kind?: CardKind } = {},
): CardDef {
  return {
    id,
    setId,
    name,
    subtitle,
    color,
    rarity,
    cost,
    motif,
    kind: extras.kind ?? 'Character',
    power: extras.power,
    counter: extras.counter,
  };
}

